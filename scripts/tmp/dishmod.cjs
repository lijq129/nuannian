const DISH_ALIAS = {
  '水煮蛋': '煮鸡蛋',
  '香煎鸡胸': '香煎鸡胸肉',
  '手撕鸡丝黄瓜': '手撕鸡丝',
  '清蒸鸡胸': '蒸鸡胸'
};

/* 通用结果：把别名解析成真正的条目 */
function resolveDish(name) {
  const raw = String(name || '');
  const key = raw.replace(/[（(][^）)]*[）)]/g, '').replace(/\s+/g, '').trim();
  const direct = DISH_ALIAS[key] || key;
  if (DISHES[direct]) return { key: direct, item: DISHES[direct] };
  let target = DISHES[key];
  if (target) return { key: key, item: target };
  /* 包含匹配：处理带修饰词的写法（如"清炒油麦菜" vs "炒油麦菜"） */
  const keys = Object.keys(DISHES);
  let best = null, bestLen = 0;
  keys.forEach(k => {
    if (k.length < 2) return;
    if ((key.indexOf(k) >= 0 || k.indexOf(key) >= 0) && k.length > bestLen) { best = k; bestLen = k.length; }
  });
  if (best) {
    let item = DISHES[best];
    while (item && item.link && DISHES[item.link]) item = DISHES[item.link];
    return { key: best, item: DISHES[best], loose: true };
  }
  return null;
}

/* 顺着 link 取到真正的做法 */
function dishBody(key) {
  let item = DISHES[key];
  let hops = 0;
  while (item && item.link && DISHES[item.link] && hops < 5) { item = DISHES[item.link]; hops++; }
  return item || null;
}

module.exports = { DISHES: DISHES, dishBody: dishBody, resolveDish: resolveDish };
